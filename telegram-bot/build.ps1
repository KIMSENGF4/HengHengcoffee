# Builds worker.js = your menu (js/data.js) + the bot code (bot.js).
# Run this after you change the menu, then paste worker.js into Cloudflare again.
#   Right-click build.ps1 -> "Run with PowerShell"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$data = Get-Content -Raw -Encoding UTF8 (Join-Path $here "..\js\data.js")
$bot  = Get-Content -Raw -Encoding UTF8 (Join-Path $here "bot.js")
$header = "/* AUTO-GENERATED by build.ps1 from js/data.js + telegram-bot/bot.js. Edit those files, not this one. */`r`n`r`n"
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText((Join-Path $here "worker.js"), $header + $data + "`r`n`r`n" + $bot, $utf8)
Write-Host "worker.js updated."
